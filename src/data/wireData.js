// 電線1本の断面積(mm²)。丸形はπ(d/2)²、平形は幅×厚さ
export const wireArea = (val) => (typeof val === "object" ? val.w * val.h : Math.PI * Math.pow(val / 2, 2));
// 外径の表示文字列。丸形は「Xmm」、平形は「W×Hmm」
export const wireOuterLabel = (val) => (typeof val === "object" ? `${val.w}×${val.h}mm` : `${val}mm`);
